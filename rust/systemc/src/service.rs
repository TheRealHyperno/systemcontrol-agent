//! systemd support: hand the agent to systemd (systemd_service.py port).
//!
//!   systemc service install [--profile <id>] [--linger] [--system]
//!   systemc service uninstall
//!   systemc service status
//!
//! User mode is the default (a user unit + `default.target`), `--system`
//! writes a system-wide unit under /etc/systemd/system (needs root).

use serde_json::{json, Value};
use std::path::PathBuf;

fn unit_name(profile: Option<&str>) -> String {
    match profile {
        Some(p) if !p.is_empty() && p != "default" => format!("systemc-{p}"),
        _ => "systemc.service".to_string(),
    }
}

fn user_unit_dir() -> PathBuf {
    // XDG_CONFIG_HOME, or ~/.config  (like systemd_service.py)
    std::env::var("XDG_CONFIG_HOME").map(PathBuf::from).unwrap_or_else(|_| {
        let home = std::env::var("HOME").unwrap_or_else(|_| ".".into());
        PathBuf::from(home).join(".config")
    }).join("systemd").join("user")
}

fn home_dir() -> String {
    std::env::var("HOME").unwrap_or_else(|_| "/root".into())
}

fn unit_contents(profile: Option<&str>, system: bool) -> String {
    let home = home_dir();
    let exec = exec_line_with_profile(profile);
    let wanted = if system { "multi-user.target" } else { "default.target" };
    format!(
        "# Generated by systemc (rust) — edit freely, re-run 'systemc service install' to regenerate\n\
        [Unit]\n\
        Description=SystemC agent ({}) — the Rust rewrite\n\
        After=network-online.target\n\
        Wants=network-online.target\n\
        \n\
        [Service]\n\
        ExecStart={exec}\n\
        WorkingDirectory={home}\n\
        Restart=on-failure\n\
        RestartSec=5\n\
        Environment=SYSTEMC_HOME={home}\n\
        \n\
        [Install]\n\
        WantedBy={wanted}\n",
        crate::version::SYSTEMC_DISPLAY,
    )
}

fn exec_line_with_profile(profile: Option<&str>) -> String {
    let bin = std::env::current_exe()
        .map(|p| p.display().to_string())
        .unwrap_or_else(|_| "/usr/bin/systemc".to_string());
    match profile {
        Some(p) if !p.is_empty() && p != "default" => format!("{bin} run --profile {p}"),
        _ => format!("{bin} run"),
    }
}

fn sh(cmd: &str, args: &[&str]) -> Value {
    match std::process::Command::new(cmd).args(args).output() {
        Ok(o) => json!({
            "ok": o.status.success(),
            "stdout": String::from_utf8_lossy(&o.stdout).trim().to_string(),
            "stderr": String::from_utf8_lossy(&o.stderr).trim().to_string(),
        }),
        Err(e) => json!({"ok": false, "error": e.to_string()}),
    }
}

pub struct ServiceOpts {
    pub profile: Option<String>,
    pub linger: bool,
    pub system: bool,
}

pub fn parse_service_args(args: &[String], action: &str) -> ServiceOpts {
    let mut opt = ServiceOpts { profile: None, linger: false, system: false };
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--profile" | "-p" => opt.profile = it.next().cloned(),
            "--linger" if action == "install" => opt.linger = true,
            "--system" => opt.system = true,
            _ => {}
        }
    }
    opt
}

pub fn install(profile: Option<String>, linger: bool, system: bool) -> Value {
    let name = unit_name(profile.as_deref());
    let dir = if system {
        PathBuf::from("/etc/systemd/system")
    } else {
        user_unit_dir()
    };
    if system && getuid30() != 0 {
        return json!({"ok": false, "error": "--system needs root (run with sudo)"});
    }
    if let Err(e) = std::fs::create_dir_all(&dir) {
        return json!({"ok": false, "error": format!("couldn't create unit dir: {e}")});
    }
    let path = dir.join(&name);
    let contents = unit_contents(profile.as_deref(), system);
    if let Err(e) = std::fs::write(&path, contents) {
        return json!({"ok": false, "error": format!("couldn't write {}: {e}", path.display())});
    }
    println!("✓ wrote {}", path.display());

    let daemon = if system {
        sh("systemctl", &["daemon-reload"])
    } else {
        sh("systemctl", &["--user", "daemon-reload"])
    };
    if !daemon["ok"].as_bool().unwrap_or(false) {
        return json!({"ok": false, "error": "daemon-reload failed", "detail": daemon});
    }
    let enable = if system {
        sh("systemctl", &["enable", "--now", &name])
    } else {
        sh("systemctl", &["--user", "enable", "--now", &name])
    };
    if !enable["ok"].as_bool().unwrap_or(false) {
        return json!({"ok": false, "error": "enable failed", "detail": enable});
    }

    let linger_out = if linger && !system {
        let user = std::env::var("USER").unwrap_or_default();
        let r = sh("loginctl", &["enable-linger", &user]);
        if !r["ok"].as_bool().unwrap_or(false) {
            eprintln!("warning: enable-linger failed ({}), service only starts at login", r["error"].as_str().unwrap_or("see stderr"));
        }
        Some(r)
    } else {
        None
    };

    println!("\n✓ {name} installed and started.");
    println!("  status:  systemctl {} status {name}", if system { "" } else { "--user" });
    println!("  logs:    journalctl {} -f -u {name}", if system { "" } else { "--user" });
    json!({"ok": true, "unit": name, "path": path.display().to_string(), "linger": linger_out})
}

fn getuid30() -> u32 {
    std::process::Command::new("id").arg("-u").output()
        .ok()
        .and_then(|o| String::from_utf8(o.stdout).ok())
        .and_then(|s| s.trim().parse().ok())
        .unwrap_or(1000)
}

pub fn uninstall(profile: Option<String>, system: bool) -> Value {
    let name = unit_name(profile.as_deref());
    let out = if system {
        let _ = sh("systemctl", &["disable", "--now", &name]);
        let path = PathBuf::from("/etc/systemd/system").join(&name);
        std::fs::remove_file(&path).ok();
        sh("systemctl", &["daemon-reload"])
    } else {
        let _ = sh("systemctl", &["--user", "disable", "--now", &name]);
        let path = user_unit_dir().join(&name);
        std::fs::remove_file(&path).ok();
        sh("systemctl", &["--user", "daemon-reload", "--reset-failed"])
    };
    println!("✓ {name} uninstalled.");
    json!({"ok": out["ok"].as_bool().unwrap_or(false), "unit": name})
}

pub fn status() -> String {
    let profile: Option<String> = std::env::var("SYSTEMC_PROFILE_ID").ok()
        .filter(|p| !p.is_empty() && p != "default");
    let name = unit_name(profile.as_deref());
    match sh("systemctl", &["--user", "status", &name]) {
        v if v["ok"].as_bool().unwrap_or(false) => v["stdout"].as_str().unwrap_or_default().to_string(),
        v => format!("(inactive or not installed — run `systemc service install`)\n{}", v["stderr"].as_str().unwrap_or_default()),
    }
}
