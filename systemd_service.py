"""
systemd user-service support: start the bot(s) at login (or at boot, with lingering).

    python3 systemd_service.py install [--profile <id>] [--linger]
    python3 systemd_service.py uninstall [--profile <id>]
    python3 systemd_service.py status  [--profile <id>]

Unit names:
    systemc.service            (default profile)
    systemc-<id>.service       (per-profile instances)

User units run under your account (no root needed) and are started by
systemd's user session at login. With --linger, `loginctl enable-linger`
keeps them running from boot, even before you log in.
"""

import os
import subprocess
import sys

AUTOSTROP = None  # (no-op; keeps the module stdlib-only like i18n.py)


def _user_dir() -> str:
    xdg = os.environ.get("XDG_CONFIG_HOME", "")
    return os.path.join(xdg if os.path.isabs(xdg) else os.path.expanduser("~/.config"), "systemd", "user")


def _run(cmd, quiet=True):
    try:
        return subprocess.run(cmd, stdout=subprocess.DEVNULL if quiet else None,
                              stderr=subprocess.PIPE, text=True).returncode
    except FileNotFoundError:
        return -1


def unit_name(profile: str = "default") -> str:
    return "systemc.service" if (profile or "default") == "default" else f"systemc-{profile}.service"


def _is_enabled(profile: str = "default") -> bool:
    return _run(["systemctl", "--user", "is-enabled", unit_name(profile)]) == 0


def unit_text(profile: str = "default", linger: bool = False) -> str:
    here = os.path.dirname(os.path.abspath(__file__))
    python = sys.executable or "python3"
    args = " ".join(p for p in [
        f"{python} {os.path.join(here, 'main.py')}",
        *([f"--profile {profile}"] if (profile and profile != "default") else []),
    ] if p)
    return f"""\
# Generated by systemc (python) systemd_service.py — safe to delete.
[Unit]
Description=SystemC Drovex bot{' (' + profile + ')' if profile not in ('', 'default') else ''}
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
WorkingDirectory={here}
ExecStart={args}
Restart=on-failure
RestartSec=5
# keep noisy bot output visible in the journal
JournalTarget=systemc

[Install]
WantedBy=default.target
"""


def install(profile: str = "default", linger: bool = False) -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    env = os.path.join(here, ".env")
    if not os.path.exists(env):
        print("no .env found — run the bot once (or the control panel's Setup) first")
        return 1
    with open(env) as f:
        configured = any(k.split("=")[0].strip() in ("DISCORD_BOT_TOKEN", "STOAT_BOT_TOKEN")
                         and k.split("=", 1)[1].strip() for k in f if "=" in k)
    if not configured:
        print("no DISCORD_BOT_TOKEN / STOAT_BOT_TOKEN in .env — nothing to start")
        return 1

    d = _user_dir()
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, unit_name(profile))
    with open(path, "w") as f:
        f.write(unit_text(profile))
    _run(["systemctl", "--user", "daemon-reload"])
    if _run(["systemctl", "--user", "enable", "--now", unit_name(profile)]) != 0:
        print("enable failed — is a user systemd session available? (loginctl show-user $USER)")
        return 1
    if linger:
        _run(["loginctl", "enable-linger", os.environ.get("USER", "")])
        print("lingering enabled: the bot starts at boot, before login")
    print(f"installed: {path}")
    print(f"status:    systemctl --user status {os.path.basename(unit_name(profile))}")
    print("log:       journalctl --user -u " + os.path.basename(unit_name(profile)) + " -f")
    return 0


def uninstall(profile: str = "default") -> int:
    name = unit_name(profile)
    _run(["systemctl", "--user", "disable", "--now", name])
    try:
        os.remove(os.path.join(_user_dir(), name))
    except FileNotFoundError:
        print(f"{name} was not installed")
        return 0
    _run(["systemctl", "--user", "daemon-reload"])
    print(f"removed {name}")
    return 0


def status(profile: str = "default") -> int:
    name = unit_name(profile)
    print(f"unit:      {os.path.join(_user_dir(), name)}")
    print("installed:", "yes" if os.path.exists(os.path.join(_user_dir(), name)) else "no")
    print("enabled:  ", "yes" if _is_enabled(profile) else "no")
    code = _run(["systemctl", "--user", "is-active", name], quiet=False)
    return 0


if __name__ == "__main__":
    argv = sys.argv[1:]
    action = argv[0] if argv else "status"
    if action in ("install", "uninstall", "status"):
        profile = "default"
        linger = "--linger" in argv
        try:
            profile = argv[argv.index("--profile") + 1]
        except ValueError:
            pass
        sys.exit({"install": lambda: install(profile, linger),
                  "uninstall": lambda: uninstall(profile),
                  "status": lambda: status(profile)}[action]())
    print("usage: python3 systemd_service.py install [--profile <id>] [--linger] | uninstall | status")
