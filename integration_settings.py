"""
Shared settings layer for integrations: reading/writing .env and switching
integrations on and off.

Everything that changes integration settings goes through here — the control
panel's Integrations tab and the HTTP API (integrations_api.py) both call these
functions, so they can't disagree about validation or file format. Standard
library only (no tkinter, FastAPI or discord), so it imports anywhere.

Every function takes an optional env_path (default: .env next to this file).
Changes are written to .env and take effect the next time the bot starts.
"""

from __future__ import annotations

import os
import secrets
import tempfile
from typing import Optional

import integrations

APP_DIR = os.path.dirname(os.path.abspath(__file__))
ENV_PATH = os.path.join(APP_DIR, ".env")
API_TOKEN_KEY = "SYSTEMC_API_TOKEN"


class SettingsError(ValueError):
    """The requested change is invalid (bad ID, unknown name, ...). str(e) is user-facing."""


# ── .env file ────────────────────────────────────────────────────────────────

def load_env(env_path: Optional[str] = None) -> dict:
    path = env_path or ENV_PATH
    env: dict = {}
    if os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, _, v = line.partition("=")
                env[k.strip()] = v.strip()
    return env


def save_env(env: dict, env_path: Optional[str] = None) -> None:
    """Rewrite .env (empty values are dropped). Written to a temp file first and
    swapped in, so a crash can't leave a half-written .env."""
    path = env_path or ENV_PATH
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(os.path.abspath(path)), prefix=".env.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write("# systemc config — generated by control_panel.py\n")
            for k, v in env.items():
                if v != "":
                    f.write(f"{k}={v}\n")
        os.replace(tmp, path)
    except Exception:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def env_list(env: dict, key: str) -> list[str]:
    """A comma/semicolon-separated .env value as a list."""
    return [x.strip() for x in env.get(key, "").replace(";", ",").split(",") if x.strip()]


# ── integrations on/off ──────────────────────────────────────────────────────

def list_integrations(env_path: Optional[str] = None) -> list[dict]:
    """Every integration that declares PANEL, with its on/off state per .env."""
    return integrations.panel_entries(load_env(env_path).get("INTEGRATIONS", ""))


def get_integration(name: str, env_path: Optional[str] = None) -> dict:
    for row in list_integrations(env_path):
        if row["name"] == name:
            return row
    raise KeyError(name)


def set_enabled(name: str, on: bool, env_path: Optional[str] = None) -> dict:
    """Switch an integration on or off in .env and return its updated row.
    KeyError if there is no such integration (or it has no PANEL field)."""
    get_integration(name, env_path)                      # raises KeyError
    env = load_env(env_path)
    env["INTEGRATIONS"] = integrations.set_enabled(
        env.get("INTEGRATIONS", ""), name, bool(on), integrations.available_names())
    save_env(env, env_path)
    return get_integration(name, env_path)


# ── declared settings (PANEL "fields") ───────────────────────────────────────
# An integration lists its settings as data; this is the one place that reads,
# validates and saves them, so the control panel and the HTTP API can't disagree.

import re

SECRET_MASK = "••••••••"


def _fields_of(name: str, env_path: Optional[str] = None) -> list[dict]:
    row = get_integration(name, env_path)               # KeyError if unknown
    return [f for item in row["submenu"] for f in item["fields"]]


def _stored(field: dict, raw: Optional[str]):
    """The value as shown to callers: typed, secrets reduced to set / not set."""
    if field["type"] == "secret":
        return {"set": bool(raw)}
    return integrations.coerce(field, raw)


def get_settings(name: str, env_path: Optional[str] = None) -> dict:
    """{"name", "pages": [{id, title, description, fields: [...]}], "problems": [...]}.
    Each field carries its declaration plus "value" (what .env says, or the default) and
    "is_default". Secrets never leave this function: their value is {"set": true|false}.
    KeyError if there is no such integration."""
    row = get_integration(name, env_path)
    env = load_env(env_path)
    pages = []
    for item in row["submenu"]:
        if not item["fields"]:
            continue
        fields = []
        for f in item["fields"]:
            raw = env.get(f["key"])
            fields.append({**f, "value": _stored(f, raw), "is_default": not raw})
        pages.append({"id": item["id"], "title": item["title"],
                      "description": item["description"], "fields": fields})
    return {"name": name, "pages": pages, "problems": row["problems"]}


def _to_env(field: dict, value) -> str:
    """Validate one incoming value and return the string to store ('' = unset)."""
    key, t = field["key"], field["type"]
    label = field["label"]
    if value is None or value == "" or value == []:
        return ""                       # unset -> the default ("required" is only a hint in the UI)
    if t == "bool":
        if not isinstance(value, bool):
            raise SettingsError(f"{label} must be true or false.")
        return "true" if value else "false"
    if t == "number":
        if isinstance(value, bool):
            raise SettingsError(f"{label} must be a number.")
        try:
            n = float(value)
        except (TypeError, ValueError):
            raise SettingsError(f"{label} must be a number.")
        if n != n or n in (float("inf"), float("-inf")):
            raise SettingsError(f"{label} must be a number.")
        if field["min"] is not None and n < field["min"]:
            raise SettingsError(f"{label} must be at least {field['min']}.")
        if field["max"] is not None and n > field["max"]:
            raise SettingsError(f"{label} must be at most {field['max']}.")
        return str(int(n)) if n.is_integer() else str(n)
    if t == "choice":
        v = str(value)
        if v not in field["choices"]:
            raise SettingsError(f"{label} must be one of: {', '.join(field['choices'])}.")
        return v
    if t == "list":
        if isinstance(value, str):
            value = value.replace(";", ",").split(",")
        if not isinstance(value, (list, tuple)):
            raise SettingsError(f"{label} must be a list.")
        items = list(dict.fromkeys(str(x).strip() for x in value if str(x).strip()))
        for x in items:
            if "," in x or "\n" in x:
                raise SettingsError(f"{label}: items can't contain commas or line breaks.")
            if field["pattern"] and not re.search(field["pattern"], x):
                raise SettingsError(f"{label}: {x!r} isn't valid.")
        return ",".join(items)
    # text / secret
    v = str(value).strip()
    if "\n" in v or "\r" in v:
        raise SettingsError(f"{label} must be a single line.")
    if field["pattern"] and not re.search(field["pattern"], v):
        raise SettingsError(f"{label} isn't valid.")
    return v


def set_settings(name: str, values: dict, env_path: Optional[str] = None) -> dict:
    """Apply {KEY: value} to .env for the integration's declared fields, all or nothing.
    A key set to None (or "") goes back to its default; keys not mentioned are untouched.
    Unknown keys raise SettingsError. Returns get_settings(name)."""
    fields = {f["key"]: f for f in _fields_of(name, env_path)}
    if not isinstance(values, dict) or not values:
        raise SettingsError("No settings were given.")
    clean = {}
    for key, value in values.items():
        if key not in fields:
            raise SettingsError(f"Unknown setting: {key}")
        clean[key] = _to_env(fields[key], value)
    env = load_env(env_path)
    for key, v in clean.items():
        env[key] = v
    save_env(env, env_path)
    return get_settings(name, env_path)


# ── API token ────────────────────────────────────────────────────────────────

def get_api_token(env_path: Optional[str] = None) -> str:
    return load_env(env_path).get(API_TOKEN_KEY, "")


def new_api_token(env_path: Optional[str] = None) -> str:
    """Create (or replace) the API token. The old one stops working immediately."""
    env = load_env(env_path)
    env[API_TOKEN_KEY] = secrets.token_urlsafe(32)
    save_env(env, env_path)
    return env[API_TOKEN_KEY]
